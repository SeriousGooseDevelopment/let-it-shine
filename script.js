const assetPath = (file) => `assets/originals/${file}`;
const featuredGallery = document.querySelector('[data-featured-gallery]');
const modalGallery = document.querySelector('[data-modal-gallery]');

function galleryCard(file, index) {
  const button = document.createElement('button');
  button.className = 'gallery-card';
  button.type = 'button';
  button.dataset.galleryIndex = allImages.indexOf(file);
  button.setAttribute('aria-label', `Open gallery image ${index + 1}`);
  button.innerHTML = `<img src="${assetPath(file)}" alt="Let It Shine Detailing work ${index + 1}" loading="lazy" />`;
  button.addEventListener('click', () => openGallery(allImages.indexOf(file)));
  return button;
}

featuredImages.slice(0, 5).forEach((file, index) => {
  featuredGallery?.appendChild(galleryCard(file, index));
});

allImages.forEach((file, index) => {
  const image = document.createElement('img');
  image.src = assetPath(file);
  image.alt = `Let It Shine Detailing gallery image ${index + 1}`;
  image.loading = 'lazy';
  image.dataset.galleryIndex = index;
  image.addEventListener('click', () => openGallery(index));
  modalGallery?.appendChild(image);
});

