const modal = document.querySelector('[data-gallery-modal]');

function openGallery(index = 0) {
  modal?.classList.add('is-open');
  modal?.setAttribute('aria-hidden', 'false');
  document.body.style.overflow = 'hidden';
  const target = modalGallery?.querySelector(`[data-gallery-index="${index}"]`);
  target?.scrollIntoView({ block: 'center' });
}

function closeGallery() {
  modal?.classList.remove('is-open');
  modal?.setAttribute('aria-hidden', 'true');
  document.body.style.overflow = '';
}

document.querySelector('[data-open-gallery]')?.addEventListener('click', () => openGallery());
document.querySelectorAll('[data-close-gallery]').forEach((button) => {
  button.addEventListener('click', closeGallery);
});
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') closeGallery();
});

const estimateForm = document.querySelector('[data-estimate-form]');
const formSteps = [...document.querySelectorAll('[data-form-step]')];
const stepIndicators = [...document.querySelectorAll('[data-step-indicator]')];
let currentStep = 1;

function setStep(step) {
  currentStep = Math.max(1, Math.min(3, step));
  formSteps.forEach((section) => {
    const active = Number(section.dataset.formStep) === currentStep;
    section.classList.toggle('is-active', active);
    section.setAttribute('aria-hidden', String(!active));
  });
  stepIndicators.forEach((indicator) => {
    indicator.classList.toggle('is-active', Number(indicator.dataset.stepIndicator) === currentStep);
  });
}

function validateCurrentStep() {
  const activeStep = formSteps.find((section) => Number(section.dataset.formStep) === currentStep);
  if (!activeStep) return true;
  return [...activeStep.querySelectorAll('input, select, textarea')].every((field) => {
    if (!field.required) return true;
    return field.reportValidity();
  });
}

document.querySelectorAll('[data-next-step]').forEach((button) => {
  button.addEventListener('click', () => {
    if (validateCurrentStep()) setStep(currentStep + 1);
  });
});

document.querySelectorAll('[data-prev-step]').forEach((button) => {
  button.addEventListener('click', () => setStep(currentStep - 1));
});

document.querySelectorAll('[data-service]').forEach((link) => {
  link.addEventListener('click', () => {
    const serviceSelect = estimateForm?.querySelector('select[name="service"]');
    const selectedService = link.dataset.service;
    if (serviceSelect && [...serviceSelect.options].some((option) => option.value === selectedService)) {
      serviceSelect.value = selectedService;
    }
  });
});

estimateForm?.addEventListener('submit', (event) => {
  event.preventDefault();
  if (!validateCurrentStep()) return;
  const data = new FormData(estimateForm);
  const name = String(data.get('name') || '').trim();
  const contact = String(data.get('contact') || '').trim();
  const vehicle = String(data.get('vehicle') || '').trim();
  const service = String(data.get('service') || '').trim();
  const message = String(data.get('message') || '').trim();
  const status = estimateForm.querySelector('[data-form-status]');
  const subject = encodeURIComponent(`Free estimate request from ${name}`);
  const body = encodeURIComponent(`Name: ${name}\nContact: ${contact}\nVehicle: ${vehicle}\nService: ${service}\n\n${message}`);
  window.location.href = `mailto:letitshinedetailing2016@gmail.com?subject=${subject}&body=${body}`;
  status.textContent = 'Your email app is opening with the estimate request ready to send.';
});

